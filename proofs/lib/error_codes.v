Lemma encode_os_err_code_in_range : forall err,
  0 <= encode_os_err_code err < 256.
Proof. destruct err; simpl; lia. Qed.

Lemma decode_encode_os_err_code : forall err,
  decode_os_err_code (encode_os_err_code err) = Some err.
Proof. destruct err; reflexivity. Qed.

Lemma encode_os_err_code_injective : forall first second,
  encode_os_err_code first = encode_os_err_code second -> first = second.
Proof.
  intros first second Heq.
  pose proof (f_equal decode_os_err_code Heq) as Hdecoded.
  rewrite !decode_encode_os_err_code in Hdecoded; congruence.
Qed.
