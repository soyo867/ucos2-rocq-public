Inductive FlagPendCaller : Type :=
| FlagPendTaskCaller (call : OsSchedCallContext)
| FlagPendInterruptCaller (view : OsExecutionView) (active : option (Z * nat)).

Definition flag_pend_non_idle_at (sg : StableGlobVars) (call : OsSchedCallContext)
  (state : UCOS2_Verify_State) : Prop :=
  exists node, state.(TskState).(inUsedTaskStates) call.(os_sched_call_stack).(stackLeaseSlot) = Some node /\
    node.(taskGeneration) = call.(os_sched_call_stack).(stackLeaseGeneration) /\
    node.(curPrio) <> sg.(osLowestPrio).

Definition flag_pend_current_ready (call : OsSchedCallContext)
  (state : UCOS2_Verify_State) : Prop :=
  exists task,
    sched_current_ready_at state.(TskState) state.(SchedState)
      call.(os_sched_call_stack).(stackLeaseSlot) task /\
    task.(taskGeneration) = call.(os_sched_call_stack).(stackLeaseGeneration).

