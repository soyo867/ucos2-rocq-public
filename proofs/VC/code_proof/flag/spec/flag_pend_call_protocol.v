Definition flag_pend_call_endpoint_observations (environment : TaskStackCallEnvironment)
  sg caller original before returned current : Prop :=
  match caller with
  | FlagPendTaskCaller _ =>
      ((kernel_call_task_source original before /\ flag_pend_current_ready original before) ->
        flag_pend_current_ready returned current) /\
      ((kernel_call_task_source original before /\ task_idle_ready sg before.(TskState)) ->
        task_idle_ready sg current.(TskState)) /\
      ((kernel_call_task_source original before /\ flag_pend_non_idle_at sg original before) ->
        flag_pend_non_idle_at sg returned current) /\
      kernel_call_normal_return original before returned current /\
      (original.(os_sched_call_origin) <> BootInvocation -> kernel_call_control_rely sg before current)
  | FlagPendInterruptCaller _ _ => True
  end.

Definition flag_pend_active_save_input environment critical local
  (active : OsSchedCallContext -> UCOS2_Verify_State -> Assertion)
  sg call mask before : Assertion :=
  os_sched_fields_save_input environment critical local sg call mask before **
  active call before.

Definition flag_pend_active_restore_input environment critical local
  (active : OsSchedCallContext -> UCOS2_Verify_State -> Assertion)
  sg call saved acquired released : Assertion :=
  os_sched_fields_restore_input environment critical local sg call saved acquired released **
  active call released.

Definition flag_pend_caller_save_input environment critical local active sg caller task_call mask state : Assertion :=
  match caller with
  | FlagPendTaskCaller actual =>
      coq_prop (actual = task_call) &&
        (flag_pend_active_save_input environment critical local active sg task_call mask state ** unmap_table_rep sg)
  | FlagPendInterruptCaller view key =>
      coq_prop (task_stack_live_coverage state.(TskState) key) &&
      (kernel_execution_view_owned environment.(task_stack_call_external)
         environment.(task_stack_call_platform) view mask **
       UCOS2_fields_inv sg state ** os_sched_fields_capsules environment local state ** active task_call state ** unmap_table_rep sg)
  end.

Definition flag_pend_caller_restore_input environment critical local active sg caller task_call
  saved acquired state : Assertion :=
  match caller with
  | FlagPendTaskCaller actual =>
      coq_prop (actual = task_call) &&
        (flag_pend_active_restore_input environment critical local active sg task_call saved acquired state ** unmap_table_rep sg)
  | FlagPendInterruptCaller view key =>
      coq_prop (task_stack_live_coverage state.(TskState) key) &&
      (critical_region_masked environment.(task_stack_call_platform) critical sg
         view.(os_execution_invocation) view.(os_execution_origin) saved acquired **
       os_execution_view_resources environment.(task_stack_call_external) view **
       UCOS2_fields_inv sg state ** os_sched_fields_capsules environment local state ** active task_call state ** unmap_table_rep sg)
  end.
