Definition task_install_selected_owner environment local sg frame call selected : Assertion :=
  (UCOS2_fields_inv sg (InstallComponent.task_install_fields_current call) **
   task_stack_fragments_rep call.(InstallComponent.task_install_fields_incoming).(stackLeaseRegion)
     call.(InstallComponent.task_install_fields_resumed) **
   (coq_prop (armv7a_continuation_binding selected /\
      task_stack_key selected.(armv7a_continuation_stack) =
        task_stack_key call.(InstallComponent.task_install_fields_incoming) /\
      (selected.(armv7a_continuation_stack).(stackLeaseRegion), selected.(armv7a_continuation_fragments)) =
        (call.(InstallComponent.task_install_fields_incoming).(stackLeaseRegion),
          call.(InstallComponent.task_install_fields_resumed)) /\
      armv7a_task_frame_slice selected /\
      task_stack_live_sp call.(InstallComponent.task_install_fields_entry).(TskState)
        (task_stack_key call.(InstallComponent.task_install_fields_incoming)) selected.(armv7a_continuation_sp)) &&
    (armv7a_task_continuation_resource environment.(task_stack_call_continuations) selected ** local selected)) **
   store_parked_continuations (InstallComponent.task_install_fields_saved_resource environment local call)
     (InstallComponent.task_install_fields_current call).(TskState).(parkedTaskStacks)) ** frame.

Lemma task_install_fields_installed_owner_selected : forall environment local sg frame call,
  InstallComponent.task_install_fields_installed_owner environment local sg call ** frame |--
  EX selected, task_install_selected_owner environment local sg frame call selected.
Proof.
  intros environment local sg frame call heap
    [owned [rest [Hjoin [Howned Hframe]]]].
  destruct Howned as [left [parked [Hjoin_parked [Hleft Hparked]]]].
  destruct Hleft as [fields_fragments [capsule [Hjoin_capsule [Hfields_fragments Hcapsule]]]].
  destruct Hcapsule as [selected [Hbinding Hcapsule]].
  exists selected; exists owned, rest; split; [exact Hjoin|]. split; [|exact Hframe].
  exists left, parked; split; [exact Hjoin_parked|]. split; [|exact Hparked].
  exists fields_fragments, capsule; split; [exact Hjoin_capsule|].
  split; [exact Hfields_fragments|]. split; assumption.
Qed.

Lemma task_install_selected_owner_tuple : forall environment local sg frame call selected heap,
  task_install_selected_owner environment local sg frame call selected heap ->
  selected.(armv7a_continuation_stack) = call.(InstallComponent.task_install_fields_incoming) /\
  selected.(armv7a_continuation_fragments) = call.(InstallComponent.task_install_fields_resumed).
Proof.
  intros environment local sg frame call selected heap
    [owned [rest [Hjoin [Howned Hframe]]]].
  destruct Howned as [left [parked [Hjoin_parked [Hleft Hparked]]]].
  destruct Hleft as [fields_fragments [capsule [Hjoin_capsule [Hfields_fragments [Hbinding Hcapsule]]]]].
  destruct Hbinding as [Hdescriptor [Hkey [Hpayload Hrest]]].
  destruct selected.(armv7a_continuation_stack) as [region slot generation].
  destruct call.(InstallComponent.task_install_fields_incoming) as [incoming_region incoming_slot incoming_generation].
  unfold task_stack_key in Hkey; cbn in Hkey, Hpayload |- *.
  injection Hkey as Hslot Hgeneration; injection Hpayload as Hregion Hfragments.
  subst; split; [reflexivity|exact Hfragments].
Qed.

(** The returned call is calculated in the constructor.  Its descriptor
    came from this exact C completion's after heap, including the original
    local capsule; equality of endpoints cannot replace that resource. *)
Inductive task_install_c_terminal_return environment local sg frame call before after sp
  (actual : sched_install_heap_fragment sg before after
    (task_slot_addr sg call.(InstallComponent.task_install_fields_incoming).(stackLeaseSlot)) sp)
  (complete : InstallComponent.task_install_c_segment environment local sg frame call before after sp actual) :
  OsSchedCallContext -> Prop :=
| TaskInstallCTerminalReturn : forall selected,
    task_install_selected_owner environment local sg frame call selected after ->
    task_install_c_terminal_return environment local sg frame call before after sp actual complete
      (kernel_selected_call selected (InstallComponent.task_install_fields_current call)).

Lemma task_install_c_terminal_return_from_completion :
  forall environment local sg frame call before after sp actual complete,
  exists returned,
    task_install_c_terminal_return environment local sg frame call before after sp actual complete returned.
Proof.
  intros environment local sg frame call before after sp actual complete.
  pose proof (proj2 (InstallComponent.task_install_c_segment_resources
    environment local sg frame call before after sp actual complete)) as Hpost.
  destruct (task_install_fields_installed_owner_selected environment local sg frame call after Hpost)
    as [selected Hselected].
  eexists; constructor; exact Hselected.
Qed.

Lemma task_install_c_terminal_return_selection :
  forall environment critical local sg observer origin frame call before after sp actual complete focus returned,
  task_install_c_terminal_return environment local sg frame call before after sp actual complete returned ->
  kernel_program_c_step_return_call environment critical sg observer origin _ _ _ _ _ _ _
    (@KernelProgramCInstall environment critical sg observer origin local _ _ _ _ _ _ _
      (@InstallComponent.TaskInstallCStep environment local sg frame call before after sp actual complete))
    focus returned.(os_sched_call_stack).
Proof.
  intros environment critical local sg observer origin frame call before after sp actual complete focus returned Hreturn.
  destruct Hreturn as [selected Howner].
  apply kernel_program_install_selected_return.
  exact (proj1 (task_install_selected_owner_tuple environment local sg frame call selected after Howner)).
Qed.

