Definition kernel_restored_stack_call original incoming fragments : OsSchedCallContext :=
  {| os_sched_call_invocation := original.(os_sched_call_invocation);
     os_sched_call_origin := original.(os_sched_call_origin);
     os_sched_call_stack := incoming;
     os_sched_call_fragments := fragments |}.

Lemma armv7a_continuation_resumed_call_tuple : forall selected original incoming fragments,
  selected.(armv7a_continuation_stack) = incoming ->
  selected.(armv7a_continuation_fragments) = fragments ->
  armv7a_continuation_resumed_call selected original = kernel_restored_stack_call original incoming fragments.
Proof.
  intros selected original incoming fragments Hstack Hfragments.
  unfold armv7a_continuation_resumed_call, kernel_restored_stack_call; rewrite Hstack, Hfragments; reflexivity.
Qed.

(** The real saved-local resource, not a normal-return equality, supplies
    the original invocation.  The selector equality is the final C return
    branch's incoming lease; intermediate installs remain unrestricted. *)
Lemma task_install_c_terminal_return_caller :
  forall environment critical sg frame call original saved acquired receipt other before after sp actual,
  let local := kernel_sched_saved_local_resource_at environment.(task_stack_call_platform) critical sg
    call.(InstallComponent.task_install_fields_entry).(TskState) original saved acquired receipt other in
  forall (complete : InstallComponent.task_install_c_segment environment local sg frame call before after sp actual),
  call.(InstallComponent.task_install_fields_incoming) = original.(os_sched_call_stack) ->
  let returned := kernel_restored_stack_call original call.(InstallComponent.task_install_fields_incoming)
    call.(InstallComponent.task_install_fields_resumed) in
  task_install_c_terminal_return environment local sg frame call before after sp actual complete returned /\
  kernel_call_task_source returned (InstallComponent.task_install_fields_current call) /\
  task_tcb_init_stack_same_call returned original.
Proof.
  intros environment critical sg frame call original saved acquired receipt other before after sp actual
    local complete Hincoming returned.
  destruct (task_install_c_terminal_return_from_completion environment local sg frame call
    before after sp actual complete) as [observed Hterminal].
  destruct Hterminal as [selected Howner].
  pose proof Howner as Hselected_owner.
  destruct (task_install_selected_owner_tuple environment local sg frame call selected after Howner)
    as [Hstack Hfragments].
  destruct Howner as [owned [rest [Hjoin [Howned Hframe]]]].
  destruct Howned as [left [parked [Hjoin_parked [Hleft Hparked]]]].
  destruct Hleft as [fields_fragments [capsule [Hjoin_capsule [Hfields_fragments [Hbinding Hcapsule]]]]].
  destruct Hcapsule as [arch_heap [local_heap [Hjoin_local [Harch Hlocal]]]].
  assert (Hselected_stack : selected.(armv7a_continuation_stack) = original.(os_sched_call_stack)) by congruence.
  unfold local in Hlocal.
  rewrite (kernel_sched_saved_local_resource_at_selected environment.(task_stack_call_platform) critical sg
    call.(InstallComponent.task_install_fields_entry).(TskState) original saved acquired receipt other
    selected Hselected_stack) in Hlocal.
  destruct Hlocal as [saved_heap [receipt_heap [Hjoin_receipt [[Hfacts Hsaved_owner] Hreceipt]]]].
  destruct Hfacts as [Hcall [Hpc [Hmask [Horigin Hactive]]]].
  assert (Hvalue : kernel_selected_call selected (InstallComponent.task_install_fields_current call) = returned).
  { unfold kernel_selected_call; rewrite Hcall.
    unfold returned; apply armv7a_continuation_resumed_call_tuple; assumption. }
  assert (Hactive_current : task_invocation_active (InstallComponent.task_install_fields_current call).(TskState)
    original.(os_sched_call_invocation) original.(os_sched_call_origin)).
  { exact (proj1 (InstallComponent.task_install_c_segment_preserves_observer
      environment local sg frame original.(os_sched_call_invocation) original.(os_sched_call_origin)
      call before after sp actual complete Hactive)). }
  pose proof complete as Hcompleted_copy; destruct Hcompleted_copy as [Hsource Hcompleted].
  destruct Hcompleted as [Hmodule Haddress Hpre Hcurrent Hrestore Hpost].
  split.
  - rewrite <- Hvalue; constructor; exact Hselected_owner.
  - split.
    + unfold kernel_call_task_source, returned, kernel_restored_stack_call; cbn.
      split; [rewrite Hincoming; exact Horigin|]. split; [exact Hactive_current|].
      unfold task_execution_current; rewrite Horigin.
      rewrite <- Hincoming; exact (proj1 Hcurrent).
    + unfold returned, kernel_restored_stack_call, task_tcb_init_stack_same_call; cbn.
      repeat split; auto.
Qed.

