Lemma os_sched_task_history_return_post_safeexec : forall environment critical active sg original mask before
  (X : OsSchedCallContext -> UCOS2_Verify_State -> Prop),
  safeExec (fun state => state = before)
    (os_sched_task_program environment critical sg original mask) X ->
  os_sched_task_history_return_post environment critical active sg original mask before |--
  EX returned current next_local,
    coq_prop (safeExec (fun state => state = current) (StateRelMonad.ret returned) X /\
      os_sched_task_current_ready returned current /\
      kernel_call_normal_return original before returned current /\ kernel_call_control_rely sg before current) &&
    (kernel_continuation_call_closed environment.(task_stack_call_continuations) kernel_program_fields_inv
      next_local sg (task_stack_call_active_key returned) returned mask current ** active returned current).
Proof.
  intros environment critical active sg original mask before X Hsafe heap
    [returned [current [next_local [Hobservations Howned]]]].
  destruct Hobservations as [Hhistory [Hsame [Hpreserved [Hsource [Hnormal Hcontrol]]]]].
  pose proof (os_sched_task_history_return_safeexec environment critical sg original mask before returned current
    X Hhistory Hsafe) as Hreturn.
  pose proof Hsource as Hready.
  exists returned, current, next_local; split; [|exact Howned].
  exact (conj Hreturn (conj Hready (conj Hnormal Hcontrol))).
Qed.

End SchedulerReturnPhaseComponent.
