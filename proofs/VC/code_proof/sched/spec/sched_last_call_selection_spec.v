(** The fourth current-C history constructor is a complete last Task
    call, not a second kind of install.  Retain its exact switch-source
    proof while interpreting the install of that same selector tuple.
    The C prefix before this install is composed with KernelProgramReturnThen
    at its actual middle heap; this lemma does not invent such a prefix. *)
Module TaskLastCallReturn.
Import CriticalComponent SequenceReturn.

Lemma os_sched_task_last_call_install_selection :
  forall environment critical sg observer origin local frame entry context saved_sp outgoing hooked incoming resumed
    (Hswitch : os_sched_requests_switch entry = true)
    (Hsave : environment.(task_stack_call_external).(os_sched_arch_save_source) context saved_sp outgoing)
    (Hhook : kernel_client_step environment.(task_stack_call_external).(os_sched_hook_action) sg
      (os_sched_save_current_sp (os_sched_prefix_state entry)
        context.(os_sched_call_stack).(stackLeaseSlot) saved_sp) hooked)
    (Hdestination : os_sched_destination_binding environment.(task_stack_call_external)
      context outgoing hooked incoming resumed),
  let call := {| InstallComponent.task_install_fields_context := context;
                 InstallComponent.task_install_fields_outgoing := outgoing;
                 InstallComponent.task_install_fields_incoming := incoming;
                 InstallComponent.task_install_fields_resumed := resumed;
                 InstallComponent.task_install_fields_entry := hooked |} in
  forall before after restored_sp
    (Hactual : sched_install_heap_fragment sg before after (task_slot_addr sg incoming.(stackLeaseSlot)) restored_sp)
    (Hcomplete : InstallComponent.task_install_c_segment environment local sg frame call
      before after restored_sp Hactual) focus selected previous,
  selected.(armv7a_continuation_call) = Some previous ->
  selected.(armv7a_continuation_stack) = incoming ->
  SourceReturn.os_sched_switch_selected_call environment.(task_stack_call_external) sg entry context
    (kernel_selected_call selected (os_sched_install_context context outgoing incoming hooked))
    (os_sched_install_context context outgoing incoming hooked)
    (conj Hswitch
      (ex_intro _ saved_sp (ex_intro _ outgoing (ex_intro _ hooked (ex_intro _ incoming
        (ex_intro _ resumed (conj Hsave (conj Hhook (conj Hdestination eq_refl))))))))) /\
  kernel_program_c_step_return_call environment critical sg observer origin _ _ _ _ _ _ _
    (@KernelProgramCInstall environment critical sg observer origin local _ _ _ _ _ _ _
      (@InstallComponent.TaskInstallCStep environment local sg frame call before after
        restored_sp Hactual Hcomplete)) focus
    (kernel_selected_call selected (os_sched_install_context context outgoing incoming hooked)).(os_sched_call_stack).
Proof.
  intros environment critical sg observer origin local frame entry context saved_sp outgoing hooked incoming resumed
    Hswitch Hsave Hhook Hdestination call before after restored_sp Hactual Hcomplete focus selected previous Hcall Hstack.
  split.
  - eapply SourceReturn.os_sched_switch_selected_call_from_continuation; eassumption.
  - rewrite kernel_selected_call_stack, Hstack; constructor.
Qed.

End TaskLastCallReturn.
